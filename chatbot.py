def process_chat_message(message, language='en', role='customer', services=None):
    """
    Process incoming chat query and return structured response.
    Automatically respects language parameter, detects script, or switches when asked.
    Supports role: 'customer' or 'worker'
    """
    clean_msg = (message or '').strip()

    # 1. Check for script detection
    script_lang = detect_script_language(clean_msg)
    # 2. Check for explicit language switch request
    switch_lang = detect_explicit_language_switch(clean_msg)

    # Resolve active language
    lang = switch_lang or script_lang or language or 'en'
    if lang not in LANGUAGES:
        lang = 'en'

    # Choose quick replies based on role
    replies_map = QUICK_REPLIES_WORKER if role == 'worker' else QUICK_REPLIES_CUSTOMER

    # If user explicitly asked for language switch with minimal other text:
    if switch_lang and len(clean_msg.split()) <= 4:
        switch_notices = {
            'en': "Switched to English! How can I assist you today?",
            'te': "భాషను తెలుగులోకి మార్చాము! ఈ రోజు మీకు ఏ సహాయం కావాలి?",
            'kn': "ಭಾಷೆಯನ್ನು ಕನ್ನಡಕ್ಕೆ ಬದಲಾಯಿಸಲಾಗಿದೆ! ಇಂದು ನಾನು ನಿಮಗೆ ಹೇಗೆ ಸಹಾಯ ಮಾಡಲಿ?",
            'hi': "भाषा बदलकर हिन्दी कर दी गई है! आज हम आपकी क्या सहायता कर सकते हैं?"
        }
        return {
            'reply': switch_notices[lang],
            'language': lang,
            'role': role,
            'quick_replies': replies_map[lang],
            'actions': []
        }

    # Match intent
    intent = match_intent(clean_msg)

    # Special handling for greeting if worker mode
    if intent == 'greeting' and role == 'worker':
        reply = KB['greeting_worker'].get(lang, KB['greeting_worker']['en'])
    else:
        content_dict = KB.get(intent, KB['fallback'])
        reply = content_dict.get(lang, content_dict.get('en', ''))

    # Prepare actions
    actions = []
    if intent in SERVICE_ACTIONS:
        s_meta = SERVICE_ACTIONS[intent]
        actions.append({
            'type': 'book_service',
            'slug': s_meta['slug'],
            'label': s_meta['action_label'].get(lang, s_meta['action_label']['en'])
        })
        actions.append({
            'type': 'view_service',
            'slug': s_meta['slug'],
            'label': {'en': 'View Details ↗', 'te': 'వివరాలు చూడండి ↗', 'kn': 'ವಿವರ ನೋಡಿ ↗', 'hi': 'विवरण देखें ↗'}.get(lang, 'View Details ↗')
        })
    elif intent in ('how_to_book', 'services_all'):
        actions.append({
            'type': 'explore_services',
            'label': {'en': 'Explore All Services ↗', 'te': 'అన్ని సేవలను చూడండి ↗', 'kn': 'ಎಲ್ಲಾ ಸೇವೆಗಳನ್ನು ವೀಕ್ಷಿಸಿ ↗', 'hi': 'सभी सेवाएं देखें ↗'}.get(lang, 'Explore All Services ↗')
        })
    elif intent == 'tracking_cancellation':
        actions.append({
            'type': 'open_dashboard',
            'label': {'en': 'Open My Dashboard ↗', 'te': 'నా డ్యాష్‌బోర్డ్ తెరవండి ↗', 'kn': 'ನನ್ನ ಡ್ಯಾಶ್‌ಬೋರ್ಡ್ ತೆರೆಯಿರಿ ↗', 'hi': 'मेरा डैशबोर्ड खोलें ↗'}.get(lang, 'Open My Dashboard ↗')
        })

    return {
        'reply': reply,
        'intent': intent,
        'language': lang,
        'role': role,
        'quick_replies': replies_map[lang],
        'actions': actions
      }
