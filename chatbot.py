def detect_script_language(text):
    """Detect language from Unicode script range if present."""
    if not text:
        return None
    # Telugu: U+0C00 to U+0C7F
    if re.search(r'[\u0C00-\u0C7F]', text):
        return 'te'
    # Kannada: U+0C80 to U+0CFF
    if re.search(r'[\u0C80-\u0CFF]', text):
        return 'kn'
    # Devanagari (Hindi): U+0900 to U+097F
    if re.search(r'[\u0900-\u097F]', text):
        return 'hi'
    return None

def detect_explicit_language_switch(text):
    """Check if the user explicitly wants to switch language."""
    t = text.lower().strip()
    if re.search(r'\b(telugu|te|తెలుగు)\b', t):
        return 'te'
    if re.search(r'\b(kannada|kn|ಕನ್ನಡ)\b', t):
        return 'kn'
    if re.search(r'\b(hindi|hi|हिन्दी|हिंदी)\b', t):
        return 'hi'
    if re.search(r'\b(english|en)\b', t):
        return 'en'
    return None

